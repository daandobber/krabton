/// The six cabinets in `CabType` order.
const CABINETS: [&[[f64; 2]]; 6] = [&HIGH_POWER_STACK, &VINTAGE_STACK, &BOUTIQUE_STACK, &LARGE_COMBO, &SMALL_COMBO, &BASS];

/// Length of the convolution buffer (`bL[90]`).
const CONV_LEN: usize = 90;
/// Only `b[0..83]` is ever shifted, so the taps past 82 of the longer
/// kernels always read zero, as in the original.
const CONV_SHIFTED: usize = 83;

/// The per-block settings every tank sample uses.
struct Settings {
    cabinet: &'static [[f64; 2]],
    color_intensity: f64,
    correctboost: f64,
    correctdrygain: f64,
    threshold: f64,
    rarefaction: f64,
    post_threshold: f64,
    post_rarefaction: f64,
    post_trim: f64,
    head_bump_freq: f64,
    lows_pad: f64,
    dcblock: f64,
    heavy: f64,
    output: f64,
    dynamicconv: f64,
    offset_a: usize,
}

#[derive(Clone, Copy)]
struct Channel {
    /// `ataLast1Sample`, `ataLast2Sample`, `ataLast3Sample`.
    ata_last: [f64; 3],
    ata_a: f64,
    ata_b: f64,
    ata_prev_diff: f64,
    b: [f64; CONV_LEN],
    last_sample: f64,
    last_half_sample: f64,
    last_post_sample: f64,
    last_post_half_sample: f64,
    post_post_sample: f64,
    d: [f64; 21],
    control: f64,
    iir_head_bump_a: f64,
    iir_head_bump_b: f64,
    iir_half_head_bump_a: f64,
    iir_half_head_bump_b: f64,
    last_ref: [f64; 7],
}

impl Channel {
    const ZERO: Self = Self {
        ata_last: [0.0; 3],
        ata_a: 0.0,
        ata_b: 0.0,
        ata_prev_diff: 0.0,
        b: [0.0; CONV_LEN],
        last_sample: 0.0,
        last_half_sample: 0.0,
        last_post_sample: 0.0,
        last_post_half_sample: 0.0,
        post_post_sample: 0.0,
        d: [0.0; 21],
        control: 0.0,
        iir_head_bump_a: 0.0,
        iir_head_bump_b: 0.0,
        iir_half_head_bump_a: 0.0,
        iir_half_head_bump_b: 0.0,
        last_ref: [0.0; 7],
    };

    /// One undersampled tank sample of one channel, up to (not including)
    /// the `lastRef` interpolation.
    fn tank(&mut self, s: &Settings, mut input: f64, flip: bool, gcount: usize) -> f64 {
        let ata_dry = input;
        let mut ata_halfway = (input + self.ata_last[0] + ((-self.ata_last[1] + self.ata_last[2]) * 0.05)) / 2.0;
        let ata_half_dry = ata_halfway;
        self.ata_last[2] = self.ata_last[1];
        self.ata_last[1] = self.ata_last[0];
        self.ata_last[0] = input;
        //setting up oversampled special antialiasing
        //pre-center code on inputSample and halfwaySample in parallel
        input = slew_clamp(input, &mut self.last_sample, s.threshold, s.rarefaction);
        ata_halfway = slew_clamp(ata_halfway, &mut self.last_half_sample, s.threshold, s.rarefaction);

        //begin center code handling conv stuff tied to 44.1K, or stuff in time domain like delays
        ata_halfway -= input;
        //retain only difference with raw signal

        let offset_a = s.offset_a as f64;
        self.d[gcount + 10] = input.abs();
        self.d[gcount] = input.abs();
        self.control += self.d[gcount] / offset_a;
        self.control -= self.d[gcount + s.offset_a] / offset_a;
        self.control -= 0.0001;
        if self.control < 0.0 {
            self.control = 0.0;
        }
        if self.control > 13.0 {
            self.control = 13.0;
        }
        let applyconv = (self.control / offset_a) * s.dynamicconv;
        //now we have a 'sag' style average to apply to the conv
        self.b.copy_within(0..CONV_SHIFTED - 1, 1);
        self.b[0] = input;
        //load conv

        let mut temp = 0.0;
        for (tap, &[base, slope]) in s.cabinet.iter().enumerate() {
            temp += self.b[tap + 1] * (base + (slope * applyconv));
        }
        input *= s.correctdrygain;
        input += temp * s.color_intensity;
        input /= s.correctboost;
        ata_halfway += input;
        //restore interpolated signal including time domain stuff now

        //second wave of Cabs style slew clamping
        input = slew_clamp(input, &mut self.last_post_sample, s.threshold, s.rarefaction);
        ata_halfway = slew_clamp(ata_halfway, &mut self.last_post_half_sample, s.threshold, s.rarefaction);

        //post-center code on inputSample and halfwaySample in parallel
        let iir = if flip { &mut self.iir_head_bump_a } else { &mut self.iir_head_bump_b };
        let mut bump = head_bump(iir, input, s.head_bump_freq, s.dcblock);
        if bump.abs() > 100.0 {
            self.clear_head_bumps();
            bump = 0.0;
        }
        bump /= s.lows_pad;
        input = (input * (1.0 - s.heavy)) + (bump * s.heavy);

        let iir = if flip { &mut self.iir_half_head_bump_a } else { &mut self.iir_half_head_bump_b };
        let mut bump = head_bump(iir, ata_halfway, s.head_bump_freq, s.dcblock);
        if bump.abs() > 100.0 {
            self.clear_head_bumps();
            bump = 0.0;
        }
        bump /= s.lows_pad;
        ata_halfway = (ata_halfway * (1.0 - s.heavy)) + (bump * s.heavy);

        //begin antialiasing section for halfway sample
        let ata_half_diff = self.antialias(ata_halfway - ata_half_dry, flip);
        //begin antialiasing section for raw sample
        let ata_diff = self.antialias(input - ata_dry, flip);

        input = ata_dry + (ata_diff + ata_half_diff + self.ata_prev_diff);
        self.ata_prev_diff = ata_diff / 2.0;
        //apply processing as difference to non-oversampled raw input

        input = slew_clamp(input, &mut self.post_post_sample, s.post_threshold, s.post_rarefaction);
        input /= s.post_trim;
        input * s.output
    }

    /// A head bump filter ran away: all four start over.
    fn clear_head_bumps(&mut self) {
        self.iir_head_bump_a = 0.0;
        self.iir_head_bump_b = 0.0;
        self.iir_half_head_bump_a = 0.0;
        self.iir_half_head_bump_b = 0.0;
    }

    /// The `ataA`/`ataB` pair, which swap roles every tank sample.
    #[inline]
    fn antialias(&mut self, diff: f64, flip: bool) -> f64 {
        let (main, other) = if flip { (&mut self.ata_a, &mut self.ata_b) } else { (&mut self.ata_b, &mut self.ata_a) };
        *main *= 0.94;
        *other *= 0.94;
        *main += diff;
        *other -= diff;
        *main * 0.94
    }
}

/// Cabs style slew clamping: a rise of more than `up` or a fall of more than
/// `down` since the last sample is cut to that.
#[inline]
fn slew_clamp(x: f64, last: &mut f64, up: f64, down: f64) -> f64 {
    let clamp = x - *last;
    let mut y = x;
    if clamp > up {
        y = *last + up;
    }
    if -clamp > down {
        y = *last - down;
    }
    *last = y;
    y
}

/// One step of a head bump filter: an integrator with a cubic soft limit and
/// a small nudge towards zero.
///
/// The original nudges with `if (iir > 0) iir -= dcblock; if (iir < 0) iir +=
/// dcblock;`, which leaves a small positive value where it is but lifts a
/// small negative one to almost `+dcblock`, so in silence the filter sits at
/// a positive offset that comes out at about -100 dB. Here a small negative
/// value stays put like a small positive one; everything else is the same.
#[inline]
fn head_bump(iir: &mut f64, x: f64, freq: f64, dcblock: f64) -> f64 {
    *iir += x * freq;
    *iir -= *iir * *iir * *iir * freq;
    if *iir > 0.0 {
        *iir -= dcblock;
        if *iir < 0.0 {
            *iir += dcblock;
        }
    } else if *iir <= -dcblock {
        *iir += dcblock;
    }
    *iir
}

pub(crate) struct Cabs {
    overallscale: f64,
    ch: [Channel; 2],
    flip: bool,
    gcount: i32,
    cycle: usize,
    fpd_l: u32,
    fpd_r: u32,
}

impl Kernel for Cabs {
    const NUM_PARAMS: usize = 6;

    fn new(sample_rate: f64) -> Self {
        let mut s = Self {
            overallscale: sample_rate / 44100.0,
            ch: [Channel::ZERO; 2],
            flip: false,
            gcount: 0,
            cycle: 0,
            fpd_l: crate::dsp::seed(),
            fpd_r: crate::dsp::seed(),
        };
        s.reset();
        s
    }

    fn reset(&mut self) {
        self.ch = [Channel::ZERO; 2];
        self.flip = false;
        self.gcount = 0;
        self.cycle = 0;
    }

    fn process(&mut self, p: &[f64], left: &mut [f32], right: &mut [f32]) {
        let cycle_end = cycle_end(self.overallscale);
        //this is going to be 2 for 88.1 or 96k, 3 for silly people, 4 for 176 or 192k
        if self.cycle > cycle_end - 1 {
            self.cycle = cycle_end - 1; //sanity check
        }

        let speaker = ((p[0] * 5.999).floor() as usize).min(5);
        let color_intensity = p[1].powf(4.0);
        let threshold = (1.0 - p[2]).powf(5.0) + 0.021; //room loud is slew
        let rarefaction = threshold.cbrt();
        let post_threshold = rarefaction.sqrt();
        let post_rarefaction = post_threshold.cbrt();
        let head_bump_freq = 0.0298 + ((1.0 - p[3]) / 8.0);
        let mut dynamicconv = 5.0;
        dynamicconv *= p[1].powf(2.0);
        dynamicconv *= p[2].powf(2.0);
        //set constants for sag speed
        let s = Settings {
            cabinet: CABINETS[speaker],
            color_intensity,
            correctboost: 1.0 + (color_intensity * 4.0),
            correctdrygain: 1.0 - color_intensity,
            threshold,
            rarefaction,
            post_threshold,
            post_rarefaction,
            post_trim: post_rarefaction.sqrt(),
            head_bump_freq,
            lows_pad: 0.12 + (head_bump_freq * 12.0),
            dcblock: head_bump_freq.powf(2.0) / 8.0,
            heavy: p[4].powf(3.0), //wet of head bump
            output: p[5].powf(2.0),
            dynamicconv,
            offset_a: 4 + ((p[3] * 5.0) as usize),
        };

        for (out_l, out_r) in left.iter_mut().zip(right.iter_mut()) {
            let input_l = noise_floor(*out_l as f64, self.fpd_l);
            let input_r = noise_floor(*out_r as f64, self.fpd_r);

            self.cycle += 1;
            if self.cycle == cycle_end {
                //hit the end point and we do a cab sample
                if self.gcount < 0 || self.gcount > 10 {
                    self.gcount = 10;
                }
                let gcount = self.gcount as usize;
                let x_l = self.ch[0].tank(&s, input_l, self.flip, gcount);
                let x_r = self.ch[1].tank(&s, input_r, self.flip, gcount);
                self.gcount -= 1;
                self.flip = !self.flip;
                fill_last_ref(&mut self.ch[0].last_ref, cycle_end, x_l);
                fill_last_ref(&mut self.ch[1].last_ref, cycle_end, x_r);
                self.cycle = 0; //reset
            }
            //we are going through our references now
            let output_l = self.ch[0].last_ref[self.cycle];
            let output_r = self.ch[1].last_ref[self.cycle];

            *out_l = dither32(output_l, &mut self.fpd_l) as f32;
            *out_r = dither32(output_r, &mut self.fpd_r) as f32;
        }
    }
}

